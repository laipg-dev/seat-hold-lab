CREATE TABLE flight_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_code VARCHAR(20) NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',

    CONSTRAINT uk_flight_seat
        UNIQUE (flight_code, seat_number),

    CONSTRAINT ck_flight_seat_status
        CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD'))
);

CREATE TABLE seat_holds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_seat_id BIGINT NOT NULL,
    customer_name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    paid_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_hold_flight_seat
        FOREIGN KEY (flight_seat_id) REFERENCES flight_seats(id),

    CONSTRAINT ck_seat_hold_status
        CHECK (status IN ('PENDING', 'PAID', 'EXPIRED')),

    CONSTRAINT ck_seat_hold_expiration
        CHECK (expires_at > created_at),

    CONSTRAINT ck_seat_hold_payment
        CHECK (
            (status = 'PAID' AND paid_at IS NOT NULL)
            OR
            (status <> 'PAID' AND paid_at IS NULL)
        )
);

CREATE INDEX idx_seat_holds_status_expires_at
    ON seat_holds (status, expires_at);

CREATE INDEX idx_seat_holds_flight_seat_id
    ON seat_holds (flight_seat_id);